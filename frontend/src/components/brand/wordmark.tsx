/**
 * Full Kenes AI logo. `tone="auto"` swaps the light/dark artwork with the theme;
 * `tone="dark"` forces the dark-mode artwork (for dark surfaces such as the auth hero).
 */
export function Wordmark({
  className,
  compact = false,
  tone = "auto",
}: {
  className?: string;
  compact?: boolean;
  tone?: "auto" | "dark";
}) {
  if (compact) return <SealMark className={className} />;
  const img = (variant: "light" | "dark", extra?: string) => (
    <Image
      src={`/brand/kenes-ai-${variant}.svg`}
      alt="Kenes AI"
      width={1545}
      height={414}
      priority
      className={cn("h-8 w-auto", extra)}
    />
  );
  return (
    <span className={cn("inline-flex items-center", className)}>
      {tone === "dark" ? (
        img("dark")
      ) : (
        <>
          {img("light", "dark:hidden")}
          {img("dark", "hidden dark:block")}
        </>
      )}
    </span>
  );
}
